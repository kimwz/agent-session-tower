export type Language = 'ko' | 'en';
export const LANGUAGE_KEY = 'agent-session-tower.language';
type Values = Record<string | number, string | number>;
export function detectLanguage(saved: string | null, browserLanguage = ''): Language {
  if (saved === 'ko' || saved === 'en') return saved;
  return /^ko(?:-|$)/i.test(browserLanguage) ? 'ko' : 'en';
}
function initialLanguage(): Language {
  // A fixed server/test default is independent of the machine running the tests.
  if (typeof window === 'undefined') return 'ko';
  let saved: string | null = null;
  try { saved = window.localStorage.getItem(LANGUAGE_KEY); } catch { /* Private browsing can disable storage. */ }
  return detectLanguage(saved, window.navigator.language);
}
