/** Only known application messages are localized; native provider output stays verbatim. */
export function translateMessage(message: string): string {
  if (!message) return message;
  if (Object.hasOwn(english, message)) return translate(message);
  const key = sourceMessages.get(message);
  if (key !== undefined) return translate(key);
  for (const template of errorTemplates) {
    const match = template.expression.exec(message);
    if (match) return translate(template.key, Object.fromEntries(template.names.map((name, index) => [name, match[index + 1]])));
  }
  return message;
}
export function setLanguage(next: Language) {
  if (next !== 'ko' && next !== 'en') return;
  language = next;
  if (typeof document !== 'undefined') document.documentElement.lang = next;
  if (typeof window !== 'undefined') {
    try { window.localStorage.setItem(LANGUAGE_KEY, next); } catch { /* Keep the language for this visit. */ }
  }
  listeners.forEach(listener => listener());
}
function subscribe(listener: () => void) { listeners.add(listener); return () => { listeners.delete(listener); }; }
export function useI18n() {
  const language = useSyncExternalStore(subscribe, getLanguage, getLanguage);
  return { language, t: translate, setLanguage };
}
